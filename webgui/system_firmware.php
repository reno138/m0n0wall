/* The automatic version check has been REMOVED.
 *
 * It opened a plaintext HTTP connection to m0n0.ch, POSTed this firewall's
 * platform and version to it, and echoed the response body straight into the
 * admin page -- unescaped. Three separate problems:
 *
 *   1. m0n0wall has been unmaintained since 2015 and that checkversion.php no
 *      longer exists, so the feature could not work regardless.
 *   2. Whoever answers for that name today could inject arbitrary HTML and
 *      script into the firewall's administration interface, from an
 *      unauthenticated position, over a connection with no integrity
 *      protection at all. Anyone on the path could do the same.
 *   3. It told a third party the platform and exact version of a firewall,
 *      unprompted and unencrypted, every time the page was opened.
 *
 * Upgrades are driven from this page: upload a signed image, and 5makeimage.sh
 * signs it with the key generated by 1makebuildenv.sh, whose public half is in
 * the image at /etc/pubkey.pem. An unsigned or wrongly-signed image is still
 * accepted, but only after an explicit override.
 *
 * A configurable update URL that fetches an image over verified TLS is a
 * feature worth having and is NOT implemented here -- doing it properly means
 * a URL field, a signature check before install, and a place to put the
 * fetched file. It must not be reinstated in the form above.
 */

if ($_POST && !file_exists($d_firmwarelock_path)) {

	$input_errors = array();
	unset($sig_warning);
	
	if (stristr($_POST['Submit'] ?? '', "Enable"))
		$mode = "enable";
	else if (stristr($_POST['Submit'] ?? '', "Disable"))
		$mode = "disable";
	else if (stristr($_POST['Submit'] ?? '', "Upgrade") || !empty($_POST['sig_override']))
		$mode = "upgrade";
	else if (!empty($_POST['sig_no']))
		unlink("{$g['ftmp_path']}/firmware.img");
		
	if (!empty($mode)) {
		if ($mode == "enable") {
			exec_rc_script("/etc/rc.firmware enable");
			touch($d_fwupenabled_path);
		} else if ($mode == "disable") {
			exec_rc_script("/etc/rc.firmware disable");
			if (file_exists($d_fwupenabled_path))
				unlink($d_fwupenabled_path);
		} else if ($mode == "upgrade") {
			if (is_uploaded_file($_FILES['ulfile']['tmp_name'] ?? '')) {
				/* verify firmware image(s) */
				if (!stristr($_FILES['ulfile']['name'], $g['fullplatform']) && empty($_POST['sig_override']))
					$input_errors[] = "The uploaded image file is not for this platform ({$g['fullplatform']}).";
				else if (!file_exists($_FILES['ulfile']['tmp_name'])) {
					/* probably out of memory for the MFS */
					$input_errors[] = "Image upload failed (out of memory?)";
					exec_rc_script("/etc/rc.firmware disable");
					if (file_exists($d_fwupenabled_path))
						unlink($d_fwupenabled_path);
				} else {
					/* move the image so PHP won't delete it */
					rename($_FILES['ulfile']['tmp_name'], "{$g['ftmp_path']}/firmware.img");
					
					/* check digital signature */
					$sigchk = verify_digital_signature("{$g['ftmp_path']}/firmware.img");
					
					if ($sigchk == 1)
						$sig_warning = "The digital signature on this image is invalid.";
					else if ($sigchk == 2)
						$sig_warning = "This image is not digitally signed.";
					else if (($sigchk == 3) || ($sigchk == 4))
						$sig_warning = "There has been an error verifying the signature on this image.";
				
					if (!verify_gzip_file("{$g['ftmp_path']}/firmware.img")) {
						$input_errors[] = "The image file is corrupt.";
						unlink("{$g['ftmp_path']}/firmware.img");
					}
				}
			} else if (!(isset($_POST['sig_override']) ||
				isset($_POST['sig_no']))) {
				$input_errors[] = "No image file has been uploaded.";
			}

			if (empty($input_errors) && !file_exists($d_firmwarelock_path) && (empty($sig_warning) || !empty($_POST['sig_override']))) {			
				/* fire up the update script in the background */
				touch($d_firmwarelock_path);
				exec_rc_script_async("/etc/rc.firmware upgrade {$g['ftmp_path']}/firmware.img");
				
				$savemsg = "The firmware is now being installed. The firewall will reboot automatically.";
			}
		}
	}
}
